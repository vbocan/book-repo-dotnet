int x = 100;

x += 10;   // echivalent cu x = x + 10
Console.WriteLine($"x += 10  → {x}");

x -= 30;   // echivalent cu x = x - 30
Console.WriteLine($"x -= 30  → {x}");

x *= 2;    // echivalent cu x = x * 2
Console.WriteLine($"x *= 2   → {x}");

x /= 4;    // echivalent cu x = x / 4
Console.WriteLine($"x /= 4   → {x}");

x %= 7;    // echivalent cu x = x % 7
Console.WriteLine($"x %= 7   → {x}");
